create or replace package builder_pattern_templates as

  /*
    Templates for the generated builder package.

    Placeholders are replaced in a single pass: generated values are never
    searched for placeholders, so they may contain "#".

    Name placeholders:
      #OWNER#              owner of the table
      #TABLE_NAME#         table name
      #PACKAGE_NAME#       name of the generated package
      #DEFAULTS_PACKAGE#   name of the (optional) hand written defaults package

    Content placeholders:
      #PARAMETERS#         one parameter per insertable column, anchored with %type
      #COLUMN_LIST#        insertable columns
      #BUILD_VALUES#       parameter references qualified with "build."
      #BUILD_ROW_VALUES#   parameter references qualified with "build_row."
      #RETURNING_LIST#     all columns of the table's %rowtype, in column order
      #NEW_ROW_DEFAULTS#   assignments of the defaults to a %rowtype record
      #ROW_LAZY_DEFAULTS#  defaults that are only evaluated when a field is null
                           (parent rows for mandatory foreign keys)
      #ROW_VALUES#         record fields (or defaults for invisible columns)

    Placeholders must not start a line: SQL*Plus treats "#" at the start of
    a line as a command prefix.
  */

  type r_placeholder_type is record(
    name varchar2(30)
    ,value clob
  );

  type t_placeholders_type is table of r_placeholder_type;


  gco_package_spec_source constant clob := q'{create or replace package #OWNER#.#PACKAGE_NAME# authid current_user as

  /*
    Test data builder for table #OWNER#.#TABLE_NAME#.
    Generated by builder_pattern_generator - do not edit, regenerate instead.

    Every parameter has a default, so a call without arguments creates a
    valid row. Defaults are taken from (in this order)
      1. the function with the same name as the column in the package
         #DEFAULTS_PACKAGE#, if it existed at generation time
      2. the column default of the table
      3. a new parent row (mandatory single column foreign keys)
      4. a generated dummy value (mandatory columns)
      5. null

    Use named notation and only pass the columns that matter for your test.
    No commit is issued.
  */

  -- Helpers for generated dummy values (unique per session and builder).
  function next_value return pls_integer;

  -- 'prefix_42', shortened to fit into i_max_length
  function dummy_text(
    i_prefix in varchar2
    ,i_max_length in pls_integer
  ) return varchar2;


  procedure build(
    #PARAMETERS#
  );

  -- Same as build, but returns the inserted row including generated values
  -- (identity columns, column defaults, values set by triggers, virtual columns).
  function build_row(
    #PARAMETERS#
  ) return #OWNER#.#TABLE_NAME#%rowtype;


  -- Record based API for reusable presets:
  --
  --   l_row := #PACKAGE_NAME#.new_row;   -- all defaults applied
  --   l_row.some_column := 'value';
  --   #PACKAGE_NAME#.build(l_row);
  --
  -- Parent rows for mandatory foreign keys are created by build/build_row,
  -- and only if the foreign key column is still null.
  function new_row return #OWNER#.#TABLE_NAME#%rowtype;

  procedure build(
    i_row in #OWNER#.#TABLE_NAME#%rowtype
  );

  function build_row(
    i_row in #OWNER#.#TABLE_NAME#%rowtype
  ) return #OWNER#.#TABLE_NAME#%rowtype;

end #PACKAGE_NAME#;}';


  gco_package_body_source constant clob := q'{create or replace package body #OWNER#.#PACKAGE_NAME# as

  g_counter pls_integer := 0;


  function next_value return pls_integer is
  begin
    g_counter := g_counter + 1;
    return g_counter;
  end next_value;


  function dummy_text(
    i_prefix in varchar2
    ,i_max_length in pls_integer
  ) return varchar2 is
    l_number constant varchar2(40) := to_char(next_value);
  begin
    if length(l_number) + 1 >= i_max_length then
      -- the last digits, zero padded: lpad alone would keep the first ones,
      -- and substr(x, -n) is null if x is shorter than n
      return lpad(substr(l_number, greatest(length(l_number) - i_max_length + 1, 1)), i_max_length, '0');
    end if;

    return substr(i_prefix, 1, i_max_length - length(l_number) - 1) || '_' || l_number;
  end dummy_text;


  procedure build(
    #PARAMETERS#
  ) is
  begin
    insert into #OWNER#.#TABLE_NAME#(
      #COLUMN_LIST#
    ) values (
      #BUILD_VALUES#
    );
  end build;


  function build_row(
    #PARAMETERS#
  ) return #OWNER#.#TABLE_NAME#%rowtype is
    l_result #OWNER#.#TABLE_NAME#%rowtype;
  begin
    insert into #OWNER#.#TABLE_NAME#(
      #COLUMN_LIST#
    ) values (
      #BUILD_ROW_VALUES#
    )
    returning
      #RETURNING_LIST#
    into l_result;

    return l_result;
  end build_row;


  function new_row return #OWNER#.#TABLE_NAME#%rowtype is
    l_row #OWNER#.#TABLE_NAME#%rowtype;
  begin
    #NEW_ROW_DEFAULTS#
    return l_row;
  end new_row;


  procedure build(
    i_row in #OWNER#.#TABLE_NAME#%rowtype
  ) is
    l_result #OWNER#.#TABLE_NAME#%rowtype;
  begin
    l_result := build_row(i_row => i_row);
  end build;


  function build_row(
    i_row in #OWNER#.#TABLE_NAME#%rowtype
  ) return #OWNER#.#TABLE_NAME#%rowtype is
    l_row #OWNER#.#TABLE_NAME#%rowtype := i_row;
    l_result #OWNER#.#TABLE_NAME#%rowtype;
  begin
    #ROW_LAZY_DEFAULTS#
    insert into #OWNER#.#TABLE_NAME#(
      #COLUMN_LIST#
    ) values (
      #ROW_VALUES#
    )
    returning
      #RETURNING_LIST#
    into l_result;

    return l_result;
  end build_row;

end #PACKAGE_NAME#;}';


  -- Replaces #NAME# by the value of the placeholder NAME, in a single pass.
  -- Unknown #...# sequences are kept as they are.
  function render(
    i_template clob
    ,i_placeholders t_placeholders_type
  ) return clob;

end builder_pattern_templates;
/
